-- ===================================
-- 养护记录管理模块建表脚本
-- 1) maintenance_record           养护记录主表（一张记录单 = 一次检查）
-- 2) maintenance_record_detail    库存检查明细表（每条库存明细的检查与养护结果）
-- 说明：养护记录关联库存明细（stock），登记本身不产生库存增减；
--       下次养护日期按明细计算，用于周期与到期提醒。
--       幂等，可重复执行。
-- ===================================

CREATE TABLE IF NOT EXISTS `maintenance_record` (
  `id`                     BIGINT       NOT NULL AUTO_INCREMENT COMMENT '养护记录唯一标识',
  `maintenance_code`       VARCHAR(32)  NOT NULL COMMENT '养护记录编号（唯一约束，格式YH-YYYYMMDD-NNN，系统自动生成，不可修改）',
  `check_time`             DATETIME     NOT NULL COMMENT '实际检查时间（人工填写，支持事后补录，与系统登记时间区分）',
  `check_type`             VARCHAR(20)  NOT NULL COMMENT '检查类型：日常检查/定期检查/特殊天气检查/复查',
  `warehouse_id`           BIGINT       DEFAULT NULL COMMENT '仓库ID（引用生产单位production_unit.prod_unit_id）',
  `warehouse_name`         VARCHAR(100) DEFAULT NULL COMMENT '仓库名称（冗余快照）',
  `checker_id`             BIGINT       DEFAULT NULL COMMENT '检查人员ID（引用系统用户user.user_id）',
  `checker_name`           VARCHAR(50)  DEFAULT NULL COMMENT '检查人员姓名（冗余快照）',
  `env_observe_info`       VARCHAR(200) DEFAULT NULL COMMENT '环境观测时间及位置（说明温湿度数据在哪里、何时测得）',
  `temperature`            DECIMAL(5,2) DEFAULT NULL COMMENT '温度（℃）',
  `humidity`               DECIMAL(5,2) DEFAULT NULL COMMENT '相对湿度（%）',
  `summary`                VARCHAR(1000) DEFAULT NULL COMMENT '总体说明（本次检查的补充说明）',
  `related_maintenance_id` BIGINT       DEFAULT NULL COMMENT '关联复查记录ID（检查类型为复查时关联原始记录）',
  `related_maintenance_code` VARCHAR(32) DEFAULT NULL COMMENT '关联复查记录编号（冗余快照）',
  `created_by`             BIGINT       DEFAULT NULL COMMENT '创建人ID',
  `updated_by`             BIGINT       DEFAULT NULL COMMENT '更新人ID',
  `created_time`           DATETIME     DEFAULT NULL COMMENT '创建时间',
  `updated_time`           DATETIME     DEFAULT NULL COMMENT '更新时间',
  `is_deleted`             TINYINT      NOT NULL DEFAULT 0 COMMENT '是否已删除：0否/1是',
  `version`                INT          NOT NULL DEFAULT 0 COMMENT '乐观锁版本号',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_maintenance_code` (`maintenance_code`),
  KEY `idx_maintenance_check_time` (`check_time`),
  KEY `idx_maintenance_warehouse_id` (`warehouse_id`),
  KEY `idx_maintenance_check_type` (`check_type`),
  KEY `idx_maintenance_related_id` (`related_maintenance_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='养护记录主表';

CREATE TABLE IF NOT EXISTS `maintenance_record_detail` (
  `id`                     BIGINT        NOT NULL AUTO_INCREMENT COMMENT '库存检查明细唯一标识',
  `maintenance_id`         BIGINT        NOT NULL COMMENT '所属养护记录ID（maintenance_record.id）',
  `stock_id`               BIGINT        DEFAULT NULL COMMENT '关联库存明细ID（stock.stock_id，物料编码+仓库+入库编号的稳定标识）',
  `material_code`          VARCHAR(50)   DEFAULT NULL COMMENT '物料编码（快照）',
  `material_name`          VARCHAR(100)  DEFAULT NULL COMMENT '物料名称（快照）',
  `spec`                   VARCHAR(200)  DEFAULT NULL COMMENT '规格（快照）',
  `category_name`          VARCHAR(50)   DEFAULT NULL COMMENT '物料分类（快照）',
  `maintenance_notes`      VARCHAR(500)  DEFAULT NULL COMMENT '养护注意事项（引用物料信息快照，只读参考）',
  `maintenance_cycle_days` INT           DEFAULT NULL COMMENT '养护周期-天（引用物料信息快照，用于计算下次养护日期）',
  `key_maintenance`        TINYINT       NOT NULL DEFAULT 0 COMMENT '是否重点养护物料：1是/0否（引用物料信息快照）',
  `batch_number`           VARCHAR(100)  DEFAULT NULL COMMENT '批号（快照）',
  `stock_in_id`            BIGINT        DEFAULT NULL COMMENT '入库单ID（stock.stock_in_id快照）',
  `in_code`                VARCHAR(50)   DEFAULT NULL COMMENT '入库编号（stock_in.in_code快照，如IN202512010001）',
  `warehouse_name`         VARCHAR(100)  DEFAULT NULL COMMENT '仓库名称（快照）',
  `unit_name`              VARCHAR(20)   DEFAULT NULL COMMENT '计量单位（快照）',
  `stock_quantity`         DECIMAL(18,4) DEFAULT NULL COMMENT '检查时库存数量（快照，与实时库存区分）',
  `shelf_location`         VARCHAR(100)  DEFAULT NULL COMMENT '货架位置（手动填写）',
  `check_scope`            VARCHAR(200)  DEFAULT NULL COMMENT '检查范围或数量（人工选填，如全部/1~3货位）',
  `packaging_status`       TINYINT       NOT NULL DEFAULT 2 COMMENT '包装与标签：1未检查/2未见异常/3发现异常/4不适用',
  `moisture_status`        TINYINT       NOT NULL DEFAULT 2 COMMENT '受潮及干湿：1未检查/2未见异常/3发现异常/4不适用',
  `pest_status`            TINYINT       NOT NULL DEFAULT 2 COMMENT '虫蛀情况：1未检查/2未见异常/3发现异常/4不适用',
  `mold_status`            TINYINT       NOT NULL DEFAULT 2 COMMENT '霉变及腐败：1未检查/2未见异常/3发现异常/4不适用',
  `oil_status`             TINYINT       NOT NULL DEFAULT 2 COMMENT '泛油情况：1未检查/2未见异常/3发现异常/4不适用',
  `color_status`           TINYINT       NOT NULL DEFAULT 2 COMMENT '色泽及外观：1未检查/2未见异常/3发现异常/4不适用',
  `odor_status`            TINYINT       NOT NULL DEFAULT 2 COMMENT '气味：1未检查/2未见异常/3发现异常/4不适用',
  `breakage_status`        TINYINT       NOT NULL DEFAULT 2 COMMENT '破碎及杂质：1未检查/2未见异常/3发现异常/4不适用',
  `stacking_status`        TINYINT       NOT NULL DEFAULT 2 COMMENT '堆放及储存条件：1未检查/2未见异常/3发现异常/4不适用',
  `other_status`           TINYINT       NOT NULL DEFAULT 2 COMMENT '其他异常：1未检查/2未见异常/3发现异常/4不适用',
  `other_description`      VARCHAR(500)  DEFAULT NULL COMMENT '其他异常具体内容（勾选发现异常时填写）',
  `moisture_content`       DECIMAL(6,2)  DEFAULT NULL COMMENT '实测含水量（%），NULL表示未测，禁止填0',
  `stack_temperature`      DECIMAL(5,2)  DEFAULT NULL COMMENT '实测垛温（℃）',
  `abnormal_description`   VARCHAR(1000) DEFAULT NULL COMMENT '异常描述（说明实际发现的情况）',
  `measures`               VARCHAR(500)  DEFAULT NULL COMMENT '养护措施（多选，逗号分隔：通风/除湿/翻垛/密封/包装整理等）',
  `measures_other`         VARCHAR(200)  DEFAULT NULL COMMENT '养护措施其他（补充说明）',
  `operator_id`            BIGINT        DEFAULT NULL COMMENT '操作人员ID（引用系统用户，可与检查人员不同）',
  `operator_name`          VARCHAR(50)   DEFAULT NULL COMMENT '操作人员姓名（冗余快照）',
  `operate_time`           DATETIME      DEFAULT NULL COMMENT '操作时间（可与检查时间不同）',
  `handle_result`          VARCHAR(1000) DEFAULT NULL COMMENT '处理结果（尚未完成时允许后续补充）',
  `remark`                 VARCHAR(500)  DEFAULT NULL COMMENT '备注',
  `last_maintenance_date`  DATE          DEFAULT NULL COMMENT '最近养护日期（本次实际检查日期）',
  `next_maintenance_date`  DATE          DEFAULT NULL COMMENT '下次养护日期（=最近养护日期+养护周期快照；为空表示不纳入周期提醒）',
  `created_by`             BIGINT        DEFAULT NULL COMMENT '创建人ID',
  `updated_by`             BIGINT        DEFAULT NULL COMMENT '更新人ID',
  `created_time`           DATETIME      DEFAULT NULL COMMENT '创建时间',
  `updated_time`           DATETIME      DEFAULT NULL COMMENT '更新时间',
  `is_deleted`             TINYINT       NOT NULL DEFAULT 0 COMMENT '是否已删除：0否/1是',
  `version`                INT           NOT NULL DEFAULT 0 COMMENT '乐观锁版本号',
  PRIMARY KEY (`id`),
  KEY `idx_mrd_maintenance_id` (`maintenance_id`),
  KEY `idx_mrd_stock_id` (`stock_id`),
  KEY `idx_mrd_next_date` (`next_maintenance_date`),
  KEY `idx_mrd_material_code` (`material_code`),
  KEY `idx_mrd_batch_number` (`batch_number`),
  KEY `idx_mrd_in_code` (`in_code`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='库存检查明细表';
